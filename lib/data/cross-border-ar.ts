export function arDrive(min: number): string {
  const h = Math.floor(min / 60);
  const m = min % 60;
  const hs = h === 1 ? "ساعة" : h === 2 ? "ساعتان" : h <= 10 ? `${h} ساعات` : `${h} ساعة`;
  if (!h) return `حوالي ${m} دقيقة`;
  return m ? `حوالي ${hs} و${m} دقيقة` : `حوالي ${hs}`;
}

/** Saudi-side places get ", السعودية" for clarity in WhatsApp prefills. */
export function arPlace(cityAr: string, saudiSide: boolean): string {
  return saudiSide && !cityAr.includes("،") ? `${cityAr}، السعودية` : cityAr;
}

