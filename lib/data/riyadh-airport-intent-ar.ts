export const RIYADH_AIRPORT_INTENT_AR: Record<string, AirportIntentAr> = Object.fromEntries(
  Object.entries(RAW_AR).map(([slug, a]) => {
    const r = ROUTES_DATA.find((x) => x.slug === slug);
    const drive = r ? arDrive(r.duration).replace(/^حوالي /, "") : "";
    const answer = r ? a.answer.replace(/\{km\}/g, String(r.distance)).replace(/\{drive\}/g, drive) : a.answer;
    return [slug, { ...a, answer }];
  }),
);

/** Arabic structured prefill — same fields as the English one. */
export function airportWhatsAppTextAr(slug: string): string {
  const en = RIYADH_AIRPORT_INTENT[slug];
  const ar = RIYADH_AIRPORT_INTENT_AR[slug];
  return (
    `السلام عليكم، أرغب بعرض سعر لنقل خاص إلى المطار.\n\n` +
    `• المسار: من الرياض إلى ${ar.destinationLabel}\n` +
    `• عنوان الاستلام: \n• تاريخ السفر: \n• وقت الاستلام: \n• عدد الركاب: \n` +
    `• الأمتعة (العدد والحجم التقريبي): \n• نوع السيارة (سيدان / SUV / فان): \n` +
    `• نوع الرحلة (ذهاب / ذهاب وعودة): \n• موعد الرحلة الجوية والصالة أو نقطة النزول المفضلة: \n• متطلبات إضافية: \n\n` +
    `أرجو تأكيد توفر السيارة والسعر الإجمالي وجدوى الرحلة` +
    (en.international ? ` وأي متطلبات حدودية` : ``) +
    ` قبل الحجز.`
  );
}
